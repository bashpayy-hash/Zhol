const { chromium } = require('playwright');
const fs = require('fs');
const OUT = __dirname + '/frames';
fs.rmSync(OUT, { recursive: true, force: true }); fs.mkdirSync(OUT);
(async () => {
  const proxy = process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY } : undefined;
  const b = await chromium.launch({ proxy });
  const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1.5, ignoreHTTPSErrors: true });
  const p = await ctx.newPage();
  await p.goto('https://zhol.live/radar?nc=' + Date.now(), { waitUntil: 'load', timeout: 90000 });
  await p.waitForTimeout(3000);
  await p.addStyleTag({ content: '.asst-bubble, .asst-panel { display: none !important }' });
  const pins = await p.evaluate(() => [...document.querySelectorAll('.map-pin')].map(e => e.getAttribute('aria-label')));
  console.log(pins.join('\n'));
  const top = await p.evaluate(() => document.querySelector('#map').getBoundingClientRect().top + scrollY - 150);
  // the still for the PDF: the map in its final state
  await p.evaluate(y => scrollTo(0, y), top); await p.waitForTimeout(5000);
  await p.screenshot({ path: __dirname + '/still-map.png' });
  await p.evaluate(() => scrollTo(0, 0)); await p.waitForTimeout(800);
  await p.reload({ waitUntil: 'load' }); await p.waitForTimeout(3000);
  await p.addStyleTag({ content: '.asst-bubble, .asst-panel { display: none !important }' });
  const top2 = await p.evaluate(() => document.querySelector('#map').getBoundingClientRect().top + scrollY - 150);
  await p.evaluate(y => scrollTo(0, y - 700), top2); await p.waitForTimeout(600);
  const cdp = await ctx.newCDPSession(p);
  const frames = [];
  cdp.on('Page.screencastFrame', async f => { frames.push(f.metadata.timestamp); fs.writeFileSync(`${OUT}/${String(frames.length).padStart(5, '0')}.jpg`, Buffer.from(f.data, 'base64')); try { await cdp.send('Page.screencastFrameAck', { sessionId: f.sessionId }); } catch (e) {} });
  await cdp.send('Page.startScreencast', { format: 'jpeg', quality: 88, everyNthFrame: 1 });
  const t0 = Date.now(); const mark = []; const at = s => mark.push([s, (Date.now() - t0) / 1000]);
  await p.waitForTimeout(500);
  await p.evaluate(y => scrollTo({ top: y, behavior: 'smooth' }), top2); at('scroll');
  await p.waitForTimeout(3600);
  await p.getByText('Alps up close', { exact: true }).first().click(); at('alps');
  await p.waitForTimeout(2800);
  const pins2 = await p.evaluate(() => [...document.querySelectorAll('.map-pin')].filter(e => e.getBoundingClientRect().width > 0).map(e => e.getAttribute('aria-label')));
  console.log('alps pins', pins2.join(' | '));
  const want = pins2.find(l => /Mont Blanc/i.test(l || '')) || pins2.find(l => /Fr[eé]jus/i.test(l || ''));
  await p.locator(`.map-pin[aria-label="${want}"]:visible`).first().click({ force: true }); at('open ' + want);
  await p.waitForTimeout(2600);
  const nxt = await p.$('[aria-label*="Next" i], .fc-next, button:has-text("›")');
  if (nxt) { await nxt.click(); at('next'); await p.waitForTimeout(5200); }
  await cdp.send('Page.stopScreencast'); await p.waitForTimeout(300);
  fs.writeFileSync(__dirname + '/times.json', JSON.stringify({ frames, mark }));
  await p.screenshot({ path: __dirname + '/still-focus.png' });
  console.log('frames', frames.length, JSON.stringify(mark));
  await b.close();
})();
